    request.AntennaDiameterM,request.AntennaHeightAglM, ...
    string(request.Service),string(request.GoesSatellite), ...
    request.BoresightLongitudeDeg,request.ExpectedBoresightElevationDeg, ...
    request.ZaRadiusKm,request.GroundOrthometricHeightM, ...
    request.AntennaOrthometricHeightM,request.GeoidUndulationM, ...
    request.AntennaEllipsoidalHeightM,string(request.DemSource), ...
    request.DemResolutionM,string(request.DemRasterId), ...
    string(request.GeoidModel),request.ProtectionCriterionDb, ...
    cfg.reporting.practicalAvailabilityPercent, ...
    request.BeamEirpDensityDbwPerMHz, ...
    VariableNames=["LatitudeDeg","LongitudeDeg","AntennaDiameterM", ...
    "AntennaHeightAglM","Service","GoesSatellite", ...
    "BoresightLongitudeDeg","BoresightElevationDeg", ...
    "GeographicZaRadiusKm","GroundOrthometricHeightM", ...
    "AntennaOrthometricHeightM","GeoidUndulationM", ...
    "AntennaEllipsoidalHeightM","DemSource","DemResolutionM", ...
    "DemRasterId","GeoidModel","ProtectionCriterionDb", ...
    "PrimaryAvailabilityPercent","BeamEirpDensityDbwPerMHz"]);
writetable(inputs,fullfile(outputFolder,"user_inputs.csv"));
end

