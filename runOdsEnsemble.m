function writeCaseArtifacts(states,resultsTable,searchTables,windowCount, ...
    plan,options)
for siteIdx = 1:size(states,1)
    for zaIdx = 1:size(states,2)
        cfg = states(siteIdx,zaIdx).fineCfg;
        caseFolder = string(cfg.output.folder);
        if ~isfolder(caseFolder), mkdir(caseFolder); end
        match = resultsTable.Site == string(cfg.site.name) & ...
            resultsTable.ZaRadiusKm == states(siteIdx,zaIdx).zaRadiusKm;
        writetable(resultsTable(match,:),fullfile(caseFolder,"result.csv"));
        writetable(searchTables{siteIdx,zaIdx}, ...
            fullfile(caseFolder,"pooled_angle_search.csv"));
        caseManifest = plan.windows(1:windowCount,:);
        writetable(caseManifest,fullfile(caseFolder,"window_manifest.csv"));
        cfg.ensemble.completedWindowCount = windowCount;
        cfg.ensemble.pooledExposureHours = ...
            windowCount*plan.windowDurationSec/3600;
        cfg.ensemble.convergenceToleranceDeg = ...
            options.ConvergenceToleranceDeg;
        jsonCfg = jsonSafeConfiguration(cfg);
        fid = fopen(fullfile(caseFolder,"configuration.json"),"w");
        assert(fid >= 0,"ODS:EnsembleConfigWrite", ...
            "Could not write configuration.json in %s.",caseFolder);
        cleanup = onCleanup(@() fclose(fid));
        fprintf(fid,"%s",jsonencode(jsonCfg,PrettyPrint=true));
        clear cleanup
    end
end
end

function jsonCfg = jsonSafeConfiguration(cfg)
jsonCfg = cfg;
jsonCfg.simulation.startTime = char(cfg.simulation.startTime, ...
    "yyyy-MM-dd'T'HH:mm:ssXXX");
jsonCfg.simulation.durationSeconds = seconds(cfg.simulation.duration);
jsonCfg.simulation = rmfield(jsonCfg.simulation,"duration");
if isfield(jsonCfg,"ensemble")
    jsonCfg.ensemble.referenceEpoch = char(cfg.ensemble.referenceEpoch, ...
        "yyyy-MM-dd'T'HH:mm:ssXXX");
    jsonCfg.ensemble.analysisStartTime = char( ...
        cfg.ensemble.analysisStartTime,"yyyy-MM-dd'T'HH:mm:ssXXX");
    jsonCfg.ensemble.analysisDurationSeconds = seconds( ...
        cfg.ensemble.analysisDuration);
    jsonCfg.ensemble = rmfield(jsonCfg.ensemble,"analysisDuration");
end
end

