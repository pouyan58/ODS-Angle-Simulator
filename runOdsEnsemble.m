function [status,statusNote] = resultStatus(resultsTable,converged)
row = resultsTable(1,:);
if converged
    status = "CONVERGED";
    statusNote = "The primary pair met the protection criterion and the configured angle-stability test.";
else
    status = "PROVISIONAL - MAXIMUM WINDOWS REACHED";
    statusNote = "Do not treat this pair as stable; increase MaximumWindowCount and rerun.";
end
if ~row.Feasible
    status = "NO FEASIBLE PAIR FOUND";
    statusNote = "The reported pair is the least-exceeding search candidate, not a protective solution.";
elseif row.SearchBoundaryFlag
    status = "PROVISIONAL - SEARCH BOUNDARY";
    statusNote = "The selected pair reached a nonphysical local search boundary.";
end
end

